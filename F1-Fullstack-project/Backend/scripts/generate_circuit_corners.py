#!/usr/bin/env python3
"""Generate ``frontend/src/data/circuitCorners.ts`` from MultiViewer data.

MultiViewer's circuit endpoint exposes every corner as a distance from the
start/finish line (``length``) plus a drawing position.  The canonical circuit
files bundled with the app can be rotated and rescaled, so the drawing position
is not portable.  The distance is: normalising it by the API's own path length
gives a fraction of the lap that can be sampled on any geometry of the same
circuit.

Run from anywhere:

    python Backend/scripts/generate_circuit_corners.py

The script is intentionally offline-friendly: it only runs when the bundled
corner table needs refreshing.  The app reads the generated TypeScript file at
build time and never calls MultiViewer itself.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

USER_AGENT = "FastF1/3.7.0"
API = "https://api.multiviewer.app/api/v1/circuits/{key}/{year}"

ROOT = Path(__file__).resolve().parents[2]
DATA_DIR = ROOT / "Backend" / "data" / "circuits"
DEFAULT_OUT = ROOT / "frontend" / "src" / "data" / "circuitCorners.ts"


def _request_json(key: int, year: int) -> dict[str, Any] | None:
    request = urllib.request.Request(API.format(key=key, year=year), headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(request, timeout=45) as response:
            if response.status != 200:
                return None
            return json.loads(response.read())
    except (urllib.error.URLError, TimeoutError, json.JSONDecodeError):
        return None


def fetch_circuit(key: int) -> dict[str, Any] | None:
    for year in (2026, 2025, 2024):
        payload = _request_json(key, year)
        if payload and payload.get("corners"):
            return payload
    return None


def path_length(xs: list[float], ys: list[float]) -> float:
    if len(xs) < 2:
        return 0.0
    total = 0.0
    for index in range(1, len(xs)):
        total += math.hypot(xs[index] - xs[index - 1], ys[index] - ys[index - 1])
    # The API usually closes the loop, but do not assume it.
    if xs[0] != xs[-1] or ys[0] != ys[-1]:
        total += math.hypot(xs[0] - xs[-1], ys[0] - ys[-1])
    return total


def build_entry(source: dict[str, Any], payload: dict[str, Any] | None) -> dict[str, Any]:
    entry: dict[str, Any] = {
        "round": source["round"],
        "circuitKey": source["circuit_key"],
        "name": source["circuit_name"],
        "location": source.get("location") or "",
        "country": source.get("country") or "",
        "corners": [],
    }
    if not payload:
        return entry

    total = path_length(payload.get("x") or [], payload.get("y") or [])
    if total <= 0:
        return entry

    corners: list[dict[str, Any]] = []
    for corner in payload.get("corners") or []:
        number = corner.get("number")
        length = corner.get("length")
        if number is None or length is None:
            continue
        fraction = (float(length) / total) % 1.0
        corner_entry: dict[str, Any] = {
            "number": int(number),
            "d": round(fraction, 5),
        }
        letter = corner.get("letter")
        if letter:
            corner_entry["letter"] = str(letter)
        corners.append(corner_entry)

    corners.sort(key=lambda item: item["d"])
    entry["corners"] = corners
    entry["apiName"] = payload.get("circuitName") or ""
    return entry


def render(entries: list[dict[str, Any]]) -> str:
    lines = [
        "// Generated by Backend/scripts/generate_circuit_corners.py — do not edit by hand.",
        "// Corner distances are fractions of a lap taken from MultiViewer's circuit",
        "// endpoint, so they can be sampled on any geometry of the same circuit.",
        "",
        "import type { CircuitLookup } from './circuitPaths';",
        "",
        "export interface CircuitCorner {",
        "  /** Turn number as shown on the official circuit map. */",
        "  number: number;",
        "  /** Optional suffix for split corners such as 8A / 8B. */",
        "  letter?: string;",
        "  /** Normalised lap distance in [0, 1). */",
        "  d: number;",
        "}",
        "",
        "export interface CircuitCornerSet {",
        "  round: number;",
        "  circuitKey: number;",
        "  name: string;",
        "  location: string;",
        "  country: string;",
        "  apiName?: string;",
        "  corners: CircuitCorner[];",
        "}",
        "",
        "export const CIRCUIT_CORNERS: CircuitCornerSet[] = [",
    ]
    for entry in entries:
        compact = json.dumps(entry, ensure_ascii=False, separators=(",", ":"))
        lines.append(f"  {compact},")
    lines.extend(
        [
            "];",
            "",
            "const normalise = (value?: string | null): string =>",
            "  (value || '').normalize('NFD').replace(/[\\u0300-\\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();",
            "",
            "const matchesText = (needle: string, haystack: string): boolean => {",
            "  if (!needle || !haystack) return false;",
            "  return needle === haystack || needle.includes(haystack) || haystack.includes(needle);",
            "};",
            "",
            "/**",
            " * Resolve the numbered corners for a circuit payload.  Text aliases win over",
            " * the numeric key because the 2026 calendar reuses key 15 for two venues.",
            " */",
            "export function getCircuitCorners(lookup?: CircuitLookup | null): CircuitCorner[] {",
            "  if (!lookup) return [];",
            "  const name = normalise(lookup.name);",
            "  const location = normalise(lookup.location);",
            "  const country = normalise(lookup.country);",
            "",
            "  if (name || location || country) {",
            "    const byName = CIRCUIT_CORNERS.find((entry) => {",
            "      const aliases = [normalise(entry.name), normalise(entry.apiName), normalise(entry.location)];",
            "      return aliases.some((alias) => matchesText(name, alias));",
            "    });",
            "    if (byName) return byName.corners;",
            "",
            "    const byPlace = CIRCUIT_CORNERS.find((entry) => {",
            "      const aliases = [normalise(entry.location), normalise(entry.country)];",
            "      return aliases.some((alias) => matchesText(location, alias) || matchesText(country, alias));",
            "    });",
            "    if (byPlace) return byPlace.corners;",
            "  }",
            "",
            "  if (lookup.circuitKey !== undefined && lookup.circuitKey !== null) {",
            "    const key = Number(lookup.circuitKey);",
            "    if (!Number.isNaN(key)) {",
            "      const byKey = CIRCUIT_CORNERS.find((entry) => entry.circuitKey === key && entry.corners.length > 0);",
            "      if (byKey) return byKey.corners;",
            "    }",
            "  }",
            "",
            "  return [];",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output TypeScript file")
    args = parser.parse_args()

    sources = []
    for path in sorted(DATA_DIR.glob("*.json"), key=lambda item: int(item.stem)):
        sources.append(json.loads(path.read_text(encoding="utf-8")))

    entries: list[dict[str, Any]] = []
    seen: dict[int, str] = {}
    for source in sources:
        key = int(source["circuit_key"])
        if key in seen:
            # A duplicate key means we cannot trust the API response for this
            # venue; keep the round in the table so name lookup resolves to an
            # empty list instead of silently borrowing another circuit's turns.
            print(f"  skip round {source['round']}: key {key} already used by {seen[key]}")
            entries.append(build_entry(source, None))
            continue
        seen[key] = str(source["round"])
        payload = fetch_circuit(key)
        entry = build_entry(source, payload)
        entries.append(entry)
        status = f"{len(entry['corners'])} corners" if entry["corners"] else "NO CORNERS"
        print(f"  round {source['round']:>2} · key {key:>3} · {source['circuit_name']} · {status}")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(entries), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
